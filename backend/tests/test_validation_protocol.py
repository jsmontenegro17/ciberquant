def test_bootstrap_manual_blocks_and_determinism():
    trades = [
        dict(signal_time=BASE, unit_pnl=Decimal(1)),
        dict(signal_time=BASE, unit_pnl=Decimal(1)),
        dict(signal_time=BASE + timedelta(days=1), unit_pnl=Decimal(-1)),
    ]
    a = bootstrap(trades, "a" * 64)
    assert a == bootstrap(trades, "a" * 64)
    assert a["block_count"] == 2 and a["iterations"] == 2000
    assert a["lower_95"] == -1 and a["upper_95"] == 1
    assert str(a["point_estimate"]).startswith("0.333333333333333333")
    assert bootstrap([], "a" * 64)["lower_95"] is None


def test_verdict_precedence_and_every_gate():
    m = dict(resolved_trades=100, total_unit_pnl="10", edge_percentage_points="1")
    folds = [m] * 4
    b = dict(block_count=10, lower_95=".1")
    assert verdict(m, folds, m, b)[0] == "PASS"
    assert verdict(m, folds, {**m, "total_unit_pnl": "-10"}, b)[0] == "FAIL"
    assert verdict(m, folds, {**m, "resolved_trades": 99, "total_unit_pnl": "-10"}, b)[0] == "INCONCLUSIVE"
    assert verdict(m, folds[:2], m, b)[0] == "INCONCLUSIVE"
    assert verdict(m, folds, m, {**b, "block_count": 9})[0] == "INCONCLUSIVE"
    assert verdict(m, folds, m, {**b, "lower_95": "0"})[0] == "FAIL"
    assert verdict({**m, "edge_percentage_points": "0"}, folds, m, b)[0] == "FAIL"
    assert verdict(m, [{**m, "total_unit_pnl": "0"}] * 2 + folds[:2], m, b)[0] == "FAIL"


def test_state_chronology_inconclusive_and_replay():
    def run(i, v):
        return SimpleNamespace(
            id=i,
            status="COMPLETED",
            verdict=v,
            test_start=BASE + timedelta(days=i),
            test_end=BASE + timedelta(days=i + 1),
            created_at=BASE,
            config_sha256=str(i),
        )

    assert historical_state([run(1, "FAIL")]) == "NOT_VALIDATED"
    assert historical_state([run(2, "INCONCLUSIVE"), run(1, "PASS")]) == "HISTORICALLY_VALIDATED"
    assert historical_state([run(3, "FAIL"), run(1, "PASS"), run(2, "INCONCLUSIVE")]) == "DEGRADED"
    assert historical_state([run(3, "FAIL"), run(1, "PASS"), run(4, "PASS")]) == "HISTORICALLY_VALIDATED"
